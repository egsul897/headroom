/**
 * One Postgres database per vitest worker, cloned from a seeded template.
 *
 * DB suites used to share one database and interfere with each other in a parallel run. The gate
 * seeds ONE template database (migrate deploy + prisma/seed.ts + the coherent financial-core
 * populator), then each vitest worker gets its own copy: <template>_w<VITEST_POOL_ID>.
 *
 *   HEADROOM_TEST_PG_TEMPLATE_URL  postgres URL of the seeded template database (gate only)
 *   HEADROOM_TEST_PG_WORKERS       how many worker databases to create (= vitest --maxWorkers)
 *
 * Unset ⇒ every function here is a no-op and tests run exactly as before.
 * Plain Node; @prisma/client is resolved from the repo under test (cwd), so this file can run from
 * the gate's temp dir (tools are read from the base ref).
 */
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { pathToFileURL } from "node:url";

const IDENT = /^[a-z_][a-z0-9_]{0,40}$/;

/** Database name for worker `poolId` (1-based, VITEST_POOL_ID). */
export function workerDatabaseName(templateDb, poolId) {
  const id = Number(poolId);
  if (!IDENT.test(templateDb)) throw new Error(`pg-workers: template database name must match ${IDENT}`);
  if (!Number.isInteger(id) || id < 1 || id > 256) throw new Error(`pg-workers: bad worker id ${String(poolId)}`);
  return `${templateDb}_w${id}`;
}

/** Same server and credentials as `templateUrl`, pointed at `dbName`. */
export function withDatabase(templateUrl, dbName) {
  const u = new URL(templateUrl);
  u.pathname = `/${dbName}`;
  return u.toString();
}

export function templateDatabaseName(templateUrl) {
  return decodeURIComponent(new URL(templateUrl).pathname.replace(/^\//, ""));
}

/** The DATABASE_URL a worker should use, or null when the gate's per-worker mode is off. */
export function workerDatabaseUrl(env = process.env) {
  const t = env.HEADROOM_TEST_PG_TEMPLATE_URL?.trim();
  if (!t) return null;
  const poolId = env.VITEST_POOL_ID ?? env.VITEST_WORKER_ID;
  if (!poolId) throw new Error("pg-workers: HEADROOM_TEST_PG_TEMPLATE_URL is set but VITEST_POOL_ID is not");
  return withDatabase(t, workerDatabaseName(templateDatabaseName(t), poolId));
}

function prismaFor(url, cwd = process.cwd()) {
  const require = createRequire(path.join(cwd, "package.json"));
  const { PrismaClient } = require("@prisma/client");
  return new PrismaClient({ datasources: { db: { url } } });
}

/** (Re)create <template>_w1.._wN from the template. Sequential: CREATE DATABASE … TEMPLATE needs an idle template. */
export async function createWorkerDatabases(templateUrl, workers, { cwd } = {}) {
  const template = templateDatabaseName(templateUrl);
  const admin = prismaFor(withDatabase(templateUrl, "postgres"), cwd);
  const names = [];
  try {
    for (let i = 1; i <= workers; i++) {
      const name = workerDatabaseName(template, i);
      await admin.$executeRawUnsafe(`DROP DATABASE IF EXISTS "${name}" WITH (FORCE)`);
      await admin.$executeRawUnsafe(`CREATE DATABASE "${name}" TEMPLATE "${template}"`);
      names.push(name);
    }
  } finally {
    await admin.$disconnect();
  }
  return names;
}

export async function dropWorkerDatabases(templateUrl, names, { cwd } = {}) {
  const admin = prismaFor(withDatabase(templateUrl, "postgres"), cwd);
  try {
    for (const name of names) {
      if (!IDENT.test(name.replace(/_w\d+$/, ""))) continue;
      await admin.$executeRawUnsafe(`DROP DATABASE IF EXISTS "${name}" WITH (FORCE)`);
    }
  } finally {
    await admin.$disconnect();
  }
}

/**
 * Source of the wrapper vitest config: the repo's own vitest.config.ts plus this tool dir's per-worker
 * setup. It is written under node_modules/.pr-gate/ (gitignored, so invisible to `git status`) so it can
 * import the repo config and resolve the repo's node_modules, while the setup code comes from `toolsDir`.
 */
export function pgVitestConfigSource(toolsDir) {
  const g = JSON.stringify(path.join(toolsDir, "vitest-pg-global-setup.mjs"));
  const s = JSON.stringify(path.join(toolsDir, "vitest-pg-worker-setup.mjs"));
  return [
    "// Generated by scripts/platform/pg-workers.mjs for the pr-gate. Do not commit.",
    'import { mergeConfig } from "vitest/config";',
    'import base from "../../vitest.config";',
    `export default mergeConfig(base, { test: { globalSetup: [${g}], setupFiles: [${s}] } });`,
    "",
  ].join("\n");
}

export const PG_VITEST_CONFIG_RELATIVE = "node_modules/.pr-gate/vitest.pg.config.mts";

function cli() {
  const [cmd, toolsDir] = process.argv.slice(2);
  if (cmd !== "write-config" || !toolsDir) {
    console.error("usage: pg-workers.mjs write-config <toolsDir>   (prints the config path)");
    process.exit(2);
  }
  const target = path.join(process.cwd(), PG_VITEST_CONFIG_RELATIVE);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, pgVitestConfigSource(path.resolve(toolsDir)));
  console.log(target);
}

const invoked = process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (invoked) cli();
