/**
 * Inbound ingestion secrets for ERP connections.
 *
 * Storage rule (the same discipline CompanySourceConnection.credentialRef
 * documents, applied to a secret Headroom itself issues): the RAW token is
 * generated at provisioning, shown to the operator ONCE (the return value of
 * createErpConnection / rotateErpConnectionSecret in lib/erp/connections.ts),
 * and NEVER stored. Only its sha256 hex is persisted
 * (CompanySourceConnection.inboundSecretHash). Verification hashes the
 * presented token and compares digests in constant time.
 *
 * Why plain sha256 and not lib/auth/password.ts's scrypt: user passwords are
 * low-entropy and need a slow KDF; these tokens are 256-bit random values
 * generated by this module, where a fast hash is the standard bearer-token
 * storage scheme (and matches lib/connectors/dedup.ts's sha256 content
 * hashing). A database leak yields hashes that cannot be reversed or
 * replayed - a presented value still has to BE the token.
 */

import { createHash, randomBytes, timingSafeEqual } from "node:crypto";

/** Prefix so a leaked token is recognizable (in logs, secret scanners) as a Headroom ERP ingestion token and nothing else. */
export const ERP_TOKEN_PREFIX = "hrp_erp_";

export interface GeneratedErpSecret {
  /** The raw token - return it to the operator once, then forget it. Never persist, never log. */
  secret: string;
  /** sha256 hex of `secret` - the ONLY form that may be stored. */
  secretHash: string;
}

export function hashErpSecret(secret: string): string {
  return createHash("sha256").update(secret, "utf8").digest("hex");
}

export function generateErpSecret(): GeneratedErpSecret {
  const secret = `${ERP_TOKEN_PREFIX}${randomBytes(32).toString("hex")}`;
  return { secret, secretHash: hashErpSecret(secret) };
}

/**
 * Constant-time verification of a presented token against the stored hash.
 * Fails closed on every malformed input (missing token, missing stored
 * hash, wrong digest length) rather than throwing into the request path.
 */
export function verifyErpSecret(presented: string | null | undefined, storedHash: string | null | undefined): boolean {
  if (!presented || !storedHash) return false;
  const presentedDigest = createHash("sha256").update(presented, "utf8").digest();
  let storedDigest: Buffer;
  try {
    storedDigest = Buffer.from(storedHash, "hex");
  } catch {
    return false;
  }
  if (storedDigest.length !== presentedDigest.length) return false;
  return timingSafeEqual(presentedDigest, storedDigest);
}

/**
 * Extracts the presented token from request headers: `Authorization: Bearer
 * <token>` (preferred) or the explicit `x-headroom-erp-token` header (for
 * middleware that cannot set Authorization). Anything else - query params
 * included - is not a credential channel: tokens in URLs land in logs.
 */
export function erpTokenFromHeaders(headers: { get(name: string): string | null }): string | null {
  const authorization = headers.get("authorization");
  if (authorization) {
    const match = /^Bearer\s+(.+)$/i.exec(authorization.trim());
    if (match) return match[1]!.trim();
  }
  const explicit = headers.get("x-headroom-erp-token");
  if (explicit && explicit.trim()) return explicit.trim();
  return null;
}
